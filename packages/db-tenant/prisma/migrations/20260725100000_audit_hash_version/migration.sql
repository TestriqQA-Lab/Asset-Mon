-- Version marker for the audit-log hash recipe.
--
-- v1 hashed the mutable `assetId` column. Deleting an asset rewrites that column to
-- NULL on the asset's existing audit rows (so the history survives the cascade), which
-- changed a hashed input and permanently broke the chain from that point onwards.
--
-- v2 drops `assetId` from the hashed payload and instead snapshots the asset's identity
-- inside `detail`, which is itself hashed and never rewritten. Deleting an asset can
-- then null the column freely without invalidating anything.
--
-- Existing rows stay on v1 so entries written before this change continue to verify
-- against the recipe they were created with.
ALTER TABLE "AuditLog" ADD COLUMN IF NOT EXISTS "hashVersion" INTEGER NOT NULL DEFAULT 1;
