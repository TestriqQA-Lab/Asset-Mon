#!/usr/bin/env bash
# tools/build-deploy-archive.sh
#
# Build the archive that gets uploaded to Hostinger's "Deploy Web App".
#
# The deployed tree is not the repository. npm needs the workspace root and the
# workspace manifests to resolve @assetmon/* links, but nothing else around them --
# and docs/ describes this infrastructure while tools/ holds scripts that provision
# workspaces, neither of which belongs on a production host. See "What to deploy" in
# docs/mysql-cutover-runbook.md for what is in here and why, and
# docs/hostinger-deployment-plan.md for the deployment itself.
#
# Two things are set inside the archive only, never in the repo:
#   - a root `start` script, because Hostinger looks at the root package.json and the
#     repo's `start` lives in apps/api
#   - a no-op root `build`, because the repo's builds BOTH apps and dist ships prebuilt
#
# No .env is included. Secrets belong in the hosting panel's environment variables;
# dotenv does not override values already in the environment, so they win.
#
# Usage:
#   bash tools/build-deploy-archive.sh [output-path]
#
# Default output: dist-deploy/assetmon-api.tar.gz (gitignored)

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${1:-$ROOT/dist-deploy/assetmon-api.tar.gz}"
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

hdr(){ printf '\n\033[1m%s\033[0m\n' "$1"; }
ok() { printf '\033[32m  ✓\033[0m %s\n' "$1"; }

cd "$ROOT"

hdr "1. Build the API"
# Must happen here, not on the host: a production install has no nest/tsc/ts-node.
npm -w @assetmon/api run build >/dev/null
[ -f apps/api/dist/main.js ] || { echo "  build produced no apps/api/dist/main.js"; exit 1; }
ok "apps/api/dist built"

hdr "2. Stage the deploy tree"
cp package.json package-lock.json "$STAGE/"

mkdir -p "$STAGE/packages/db/src" "$STAGE/packages/shared"
cp packages/db/package.json packages/db/post-migrate-collations.sql "$STAGE/packages/db/"
cp -r packages/db/prisma "$STAGE/packages/db/"
# src/index.* only -- src/generated is regenerated by the root postinstall on the host.
cp packages/db/src/index.js packages/db/src/index.d.ts packages/db/src/index.ts "$STAGE/packages/db/src/"
cp packages/shared/package.json "$STAGE/packages/shared/"
cp -r packages/shared/src "$STAGE/packages/shared/"

# Nothing imports these two any more, but apps/api/package.json still declares them,
# so npm needs the directories to resolve the workspace links. Manifests are enough.
for p in db-catalog db-tenant; do
  mkdir -p "$STAGE/packages/$p"
  cp "packages/$p/package.json" "$STAGE/packages/$p/"
done

mkdir -p "$STAGE/apps/api/scripts"
cp apps/api/package.json "$STAGE/apps/api/"
cp -r apps/api/dist "$STAGE/apps/api/"
# Plain JS, so unlike the .ts migration scripts this one runs on the host. It creates
# the first platform super-admin and loads ../dist/platform/platform-audit-hash.
cp apps/api/scripts/platform-bootstrap-admin.js "$STAGE/apps/api/scripts/"
ok "staged $(find "$STAGE" -type f | wc -l | tr -d ' ') files"

hdr "3. Rewrite the root scripts (archive only)"
STAGE_PKG="$STAGE/package.json" node -e '
  const fs = require("fs");
  const p = process.env.STAGE_PKG;
  const j = JSON.parse(fs.readFileSync(p, "utf8"));
  j.scripts.start = "node apps/api/dist/main.js";
  j.scripts.build = "echo \"dist is prebuilt and shipped in this archive; nothing to build\"";
  fs.writeFileSync(p, JSON.stringify(j, null, 2) + "\n");
'
ok "start -> node apps/api/dist/main.js"
ok "build -> no-op"

hdr "4. Pack"
mkdir -p "$(dirname "$OUT")"
rm -f "$OUT"
# tar, not zip: PowerShell's Compress-Archive writes backslash separators on Windows,
# which extract on Linux as single files with backslashes in the name.
tar -czf "$OUT" -C "$STAGE" .
if tar -tzf "$OUT" | grep -q '\\'; then
  echo "  archive contains backslash paths -- it will not extract correctly"
  exit 1
fi
ok "no backslash paths"

printf '\n\033[1mArchive:\033[0m %s (%s)\n' "$OUT" "$(du -h "$OUT" | cut -f1)"
cat <<'EOF'

On the host:
  npm install -w @assetmon/api --include-workspace-root --omit=dev
  npm start

The database must exist and the schema must be deployed first, or Prisma raises P1001
and the process exits. Set the environment variables in the hosting panel, not in a
.env file.
EOF
